// Losslessly pack the original TTFs and template with native Node Brotli.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { brotliCompressSync, brotliDecompressSync, constants } from "node:zlib";

const ROOT = new URL("../", import.meta.url);
const packed = {}, manifest = {};
const hash = value => createHash("sha256").update(value).digest("hex");
for (const [key, source] of Object.entries({
  regular: "public/fonts/KoPubDotum-Medium.ttf",
  bold: "public/fonts/KoPubDotum-Bold.ttf",
  criminal: "supabase/functions/instructor-documents/assets/criminal-consent.pdf",
})) {
  const original = readFileSync(new URL(source, ROOT));
  const bytes = brotliCompressSync(original, { params: { [constants.BROTLI_PARAM_QUALITY]: 11 } });
  if (!brotliDecompressSync(bytes).equals(original)) throw new Error("Asset compression is not lossless");
  packed[key] = bytes.toString("base64");
  manifest[key] = { source, sourceSha256: hash(original), packedSha256: hash(bytes),
    sourceBytes: original.length, packedBytes: bytes.length };
}
const content = `// Generated by scripts/build-edge-consent-assets.mjs; do not edit packed data.
import { brotliDecompressSync } from "node:zlib";
import type { ConsentAssets } from "../_shared/instructor-consent.ts";
export const CONSENT_ASSET_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;
export const CONSENT_PACKED_ASSETS = ${JSON.stringify(packed)} as const;
let cached: ConsentAssets | undefined;
function decode(encoded: string): Uint8Array {
  const text = atob(encoded);
  const bytes = new Uint8Array(text.length);
  for (let i = 0; i < text.length; i++) bytes[i] = text.charCodeAt(i);
  return new Uint8Array(brotliDecompressSync(bytes));
}
export function loadConsentAssets(): ConsentAssets {
  return cached ??= {
    regular: decode(CONSENT_PACKED_ASSETS.regular),
    bold: decode(CONSENT_PACKED_ASSETS.bold),
    criminal: decode(CONSENT_PACKED_ASSETS.criminal),
  };
}
`;
writeFileSync(new URL("supabase/functions/instructor-documents/consent-assets.ts", ROOT), content);
console.log(JSON.stringify({ assets: manifest, moduleBytes: Buffer.byteLength(content) }));
