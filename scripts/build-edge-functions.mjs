// Install pinned build tools with: npm ci --prefix tools/edge-functions
import { createRequire } from "node:module";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const toolDir = resolve(ROOT, "tools/edge-functions");
const require = createRequire(resolve(toolDir, "package.json"));
const { build } = require("esbuild");
const dependencies = JSON.parse(readFileSync(resolve(toolDir, "package.json"))).dependencies;
const sha256 = value => createHash("sha256").update(value).digest("hex");
export async function bundleEdgeSource(entry, output) {
  return build({
    ...buildOptions(entry, output),
  });
}
function buildOptions(entry, output) {
  return {
    absWorkingDir: ROOT, entryPoints: [entry], outfile: output,
    bundle: true, minify: true, format: "esm", platform: "neutral",
    target: "es2022", mainFields: ["module", "main"], conditions: ["browser", "deno"],
    external: ["node:*"], write: false, metafile: true, legalComments: "inline",
    banner: { js: "// Generated by scripts/build-edge-functions.mjs; edit the canonical TypeScript source." },
    plugins: pinnedPlugins(),
  };
}
function pinnedPlugins() {
  return [{
    name: "pinned-edge-imports",
    setup(builder) {
      builder.onResolve({ filter: /^npm:/ }, async args => {
        const match = args.path.match(/^npm:(@[^/]+\/[^@]+|[^@]+)@([^/]+)$/);
        if (!match || dependencies[match[1]] !== match[2]) throw new Error("Unpinned Edge dependency: " + args.path);
        return builder.resolve(match[1], { resolveDir: toolDir, kind: "import-statement" });
      });
      builder.onResolve({ filter: /^pdf-lib$/ }, () => ({ path: resolve(toolDir, "node_modules/pdf-lib/es/index.js") }));
      builder.onResolve({ filter: /^@pdf-lib\/fontkit$/ }, () => ({ path: resolve(ROOT, "supabase/functions/_shared/fontkit-edge.ts") }));
      builder.onResolve({ filter: /^brotli\/decompress\.js$/ }, () => ({ path: resolve(ROOT, "supabase/functions/_shared/brotli-edge.ts") }));
      builder.onResolve({ filter: /^\.\/instructor-consent-model$/ }, args => ({ path: resolve(args.resolveDir, "instructor-consent-model.ts") }));
    },
  }];
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
const functions = ["instructor-documents", "operation-report-ai"];
const inputs = new Set([
  "scripts/build-edge-functions.mjs", "tools/edge-functions/package.json",
  "tools/edge-functions/package-lock.json",
]);
const entries = {};
for (const name of functions) {
  const entry = `supabase/functions/${name}/index.ts`;
  const output = `supabase/functions/${name}/index.bundle.mjs`;
  const result = await bundleEdgeSource(entry, output);
  for (const path of Object.keys(result.metafile.inputs)) {
    const key = relative(ROOT, resolve(ROOT, path));
    if (!key.includes("node_modules/") && !key.startsWith("../")) inputs.add(key);
  }
  const external = result.metafile.outputs[output].imports;
  if (external.some(item => !item.path.startsWith("node:"))) throw new Error("Unexpected external runtime dependency");
  const bytes = result.outputFiles[0].contents;
  if (bytes.length >= 4_800_000) throw new Error(`${name}: bundle exceeds safe API deployment budget`);
  writeFileSync(resolve(ROOT, output), bytes);
  entries[name] = { path: output, bytes: bytes.length, sha256: sha256(bytes) };
  console.log(`${name}: ${bytes.length} bytes, pinned dependencies bundled`);
}
const sources = Object.fromEntries([...inputs].sort().map(path => [path, sha256(readFileSync(resolve(ROOT, path)))]));
writeFileSync(resolve(ROOT, "supabase/functions/bundle-manifest.json"), JSON.stringify({ version: 1, sources, entries }, null, 2) + "\n");
}
